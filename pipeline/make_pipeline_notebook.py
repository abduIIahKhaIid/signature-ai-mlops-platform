def code(src: str) -> dict:
    return {"cell_type": "code", "execution_count": None, "metadata": {}, "outputs": [], "source": src.strip("\n") + "\n"}


def markdown(src: str) -> dict:
    return {"cell_type": "markdown", "metadata": {}, "source": src.strip("\n") + "\n"}


def patch(src: str, old: str, new: str, cell: int) -> str:
    if old not in src:
        raise SystemExit(f"cell {cell}: anchor not found:\n{old}")
    return src.replace(old, new, 1)


