def build(source: Path, target: Path) -> None:
    nb = json.loads(source.read_text(encoding="utf-8"))
    cells = nb["cells"]
    src = lambda i: "".join(cells[i]["source"])  # noqa: E731

    c3 = patch(src(3), """if USE_COMET or UPLOAD_TO_S3 or UPLOAD_TO_R2:
    from google.colab import userdata
    def secret_or_none(name):
        try: return userdata.get(name)
        except Exception: return None
""", SECRETS_HELPER.lstrip("\n"), 3)

    c4 = patch(src(4), """    from google.colab import userdata
    try:
        hf_token = userdata.get('HF_TOKEN')
    except Exception:
        hf_token = None
""", "    hf_token = secret_or_none('HF_TOKEN')\n", 4)
    c4 = patch(c4, "local_dir='/content/signatureai_hf_download'", "local_dir=str(WORKDIR.parent / 'signatureai_hf_download')", 4)
    c4 = patch(c4, "    print('Pinned Hugging Face dataset commit:', HF_RESOLVED_COMMIT)\n",
               "    print('Pinned Hugging Face dataset commit:', HF_RESOLVED_COMMIT)\n" + AUTO_ZIP, 4)

    c14 = patch(src(14), "AutoImageProcessor.from_pretrained(MODEL_ID, use_fast=False)",
                "AutoImageProcessor.from_pretrained(INIT_PATH, use_fast=False)", 14)
    c14 = patch(c14, "from_pretrained(\n    MODEL_ID, num_labels", "from_pretrained(\n    INIT_PATH, num_labels", 14)

    c15 = src(15).rstrip("\n") + "\n" + SUBSET

    c16 = patch(src(16), "tags=['signature-detection', 'rtdetrv2', 'colab']",
                "tags=['signature-detection', 'rtdetrv2', RUNTIME_NAME] + (['pipeline', PIPELINE_MODE] if PIPELINE_MODE else [])", 16)
    c16 = patch(c16, "'phash_threshold': PHASH_THRESHOLD, 'ssim_threshold': SSIM_THRESHOLD\n    })",
                "'phash_threshold': PHASH_THRESHOLD, 'ssim_threshold': SSIM_THRESHOLD,\n"
                "        'pipeline_mode': PIPELINE_MODE, 'init_from': INIT_FROM, 'init_version': INIT_VERSION,\n"
                "        'max_train_images': MAX_TRAIN_IMAGES, 'max_val_images': MAX_VAL_IMAGES, 'runtime': RUNTIME_NAME,\n"
                "        'num_workers': NUM_WORKERS, 'hf_zip_filename': HF_ZIP_FILENAME\n    })", 16)

    c17 = src(17)
    assert "backup_to_s3" in c17, "cell 17 must be the fixed training cell with S3 checkpoint backups"

    c22 = patch(src(22), "artifact_path = Path('/content') / f'signature_detector_{RUN_VERSION}.zip'",
                "artifact_path = RUN_DIR.parent / f'signature_detector_{RUN_VERSION}.zip'", 22)
    c22 = patch(c22, "'best_val_map50': float(best_map50),\n    'comet_experiment_key'",
                "'best_val_map50': float(best_map50),\n"
                "    'test_map50': float(test_metrics.get('map_50', float('nan'))),\n"
                "    'recommended_threshold': globals().get('RECOMMENDED_THRESHOLD'),\n"
                "    'pipeline_mode': PIPELINE_MODE, 'init_version': INIT_VERSION,\n"
                "    'comet_experiment_key'", 22)

    out = [markdown(INTRO), copy.deepcopy(cells[1]), copy.deepcopy(cells[2]), code(DEFAULTS), code(OVERRIDE_PLACEHOLDER),
           code(c3), code(c4)]
    c12 = patch(src(12), "sample(unique_records, min(len(unique_records),6))",
                "sample(clean_records, min(len(clean_records),6))", 12)  # quarantined records have no final_split
    out += [copy.deepcopy(cells[i]) for i in range(5, 12)]          # parsing, cleaning, leakage gate
    out += [code(c12), copy.deepcopy(cells[13])]                    # GT preview, training markdown
    out += [code(INIT_WEIGHTS), code(c14), code(c15), code(c16), code(c17)]
    out += [copy.deepcopy(cells[19]), copy.deepcopy(cells[20])]      # curves + test evaluation, sample prediction
    out += [code(CALIBRATION), copy.deepcopy(cells[21]), code(c22), copy.deepcopy(cells[23]), code(GATE),
            copy.deepcopy(cells[24]), code(FINAL)]
    for cell in out:
        if cell["cell_type"] == "code":
            cell["outputs"], cell["execution_count"] = [], None
    nb["cells"] = out
    nb.setdefault("metadata", {}).pop("widgets", None)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(nb, indent=1, ensure_ascii=False), encoding="utf-8")
    print(f"wrote {target} ({len(out)} cells)")


