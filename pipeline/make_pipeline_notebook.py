"""Build pipeline/train_pipeline.ipynb from the Colab training notebook.

The result runs unchanged on Colab (manual) and Kaggle (headless, started by GitHub Actions):
  * secrets from env vars, Colab Secrets, Kaggle Secrets or a private Kaggle "pipeline secrets" dataset
  * optional warm start from the S3 model alias (INIT_FROM='latest')
  * optional train/val subsets for a fast "smoke" retraining run
  * threshold calibration on the validation set
  * VALIDATION GATE: the new model is deployed (S3 alias moved) only if it passes quality checks
  * pipeline_result.json + reports copied to /kaggle/working for GitHub Actions to collect

Usage:  python pipeline/make_pipeline_notebook.py <source_notebook.ipynb> pipeline/train_pipeline.ipynb
Every patch asserts that its anchor text exists, so a changed source notebook fails loudly.
"""
